//! L'en-tête de réponse de chaque commande des services remplaçants : (numéro de commande, en-tête), triés par numéro.
//!
//! Recopié de `banc/services/reply_shapes.py` (les tables viennent des fiches : colonne « En-tête de réponse » de la
//! partie « les commandes » de chacune). C'est ce que le vrai module écrit en tête de sa réponse : le nombre de mots
//! ordinaires (résultat compris) et le nombre de mots de traduction. `modules.rs` construit chaque réponse pour qu'elle
//! ait cette forme ; les tests le vérifient pour toutes les commandes de toutes les tables.

/// Une table de formes : (commande, en-tête), triée par commande.
pub type Shapes = &'static [(u32, u32)];

/// L'en-tête de la fiche pour une commande.
pub fn lookup(table: Shapes, command: u32) -> Option<u32> {
    table.binary_search_by_key(&command, |&(c, _)| c).ok().map(|i| table[i].1)
}


